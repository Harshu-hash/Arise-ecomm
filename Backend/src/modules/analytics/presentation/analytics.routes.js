import { Router } from 'express';
import { z } from 'zod';
import { ROLES } from '../../../shared/constants/roles.js';
import { NotFoundError } from '../../../shared/errors/AppError.js';
import { sendCommand, sendData } from '../../../shared/http/respond.js';
import { validate } from '../../../shared/http/validate.js';
import { authenticate, authorize } from '../../../shared/middleware/authenticate.js';
import { requirePermission, requirePermissionBy, userHasPermission } from '../../../shared/middleware/permission.js';
import { assertPlatformWide } from '../../../shared/middleware/scope.js';
import { sellerScope } from '../../../shared/policies/ownership.js';
import { ANALYTICS_DOMAINS, getDomainAnalytics } from '../application/adminAnalytics.service.js';
import { getActionCenter, getMoneyPosition, getSummary } from '../application/adminDashboard.service.js';
import { getAnalyticsFilters, getAnalyticsView } from '../application/sellerAnalytics.service.js';
import { getSellerActivity, getSellerSummary } from '../application/sellerDashboard.service.js';

const route = (handler) => async (req, res, next) => {
  try {
    return await handler(req, res);
  } catch (error) {
    return next(error);
  }
};

const summaryQuery = z.object({ days: z.coerce.number().int().min(1).max(120).default(1) });
const analyticsQuery = z.object({ days: z.coerce.number().int().min(1).max(90).default(30) });
const domainParams = z.object({ domain: z.string() });

// Mount path: /api/admin/v1/dashboard. The admin home. Alerts are not generated by anything yet, so the feed is empty.
export function createAdminDashboardRouter() {
  const router = Router();
  router.use(authenticate, authorize(ROLES.ADMIN));
  router.get('/summary', validate({ query: summaryQuery }), requirePermission('dashboard.dashboard.view'), route(async (req, res) => {
    await assertPlatformWide(req);
    return sendData(res, await getSummary({ days: req.query.days, showFinance: await userHasPermission(req.auth.userId, 'dashboard.finance_widgets.view') }));
  }));
  router.get('/action-center', requirePermission('dashboard.action_center.view'), route(async (req, res) => {
    await assertPlatformWide(req);
    const held = new Set((await Promise.all(['sellers.application.view', 'catalog.product.approve', 'orders.order.view', 'logistics.ndr.view', 'orders.return.view', 'finance.refund.view', 'finance.payout.view']
      .map(async (key) => ((await userHasPermission(req.auth.userId, key)) ? key : null)))).filter(Boolean));
    return sendData(res, await getActionCenter((permission) => held.has(permission)));
  }));
  router.get('/alerts', requirePermission('dashboard.dashboard.view'), route(async (_req, res) => sendData(res, [], { meta: { unread: 0 } })));
  router.post('/alerts/:id/read', requirePermission('dashboard.dashboard.view'), route(async (_req, res) => sendCommand(res, { ok: true })));
  return router;
}

// Mount path: /api/admin/v1/finance. Where the platform's money is right now (the dashboard's money card).
export function createAdminMoneyRouter() {
  const router = Router();
  router.use(authenticate, authorize(ROLES.ADMIN));
  router.get('/overview', requirePermission('dashboard.finance_widgets.view'), route(async (req, res) => {
    await assertPlatformWide(req);
    return sendData(res, await getMoneyPosition());
  }));
  return router;
}

const DOMAIN_PERMISSION = {
  sales: 'reports.sales.view', customers: 'reports.sales.view', marketing: 'reports.sales.view',
  catalog: 'reports.operations.view', sellers: 'reports.operations.view', fulfilment: 'reports.operations.view', returns: 'reports.operations.view', support: 'reports.operations.view',
  finance: 'reports.finance.view',
};

// An unknown domain is a 404 for everyone; the permission guard only decides for real domains.
const unknownDomainIs404 = (req, _res, next) => next(ANALYTICS_DOMAINS.includes(req.params.domain) ? undefined : new NotFoundError('Unknown analytics domain.'));

// Mount path: /api/admin/v1/reports/analytics
export function createAdminAnalyticsRouter() {
  const router = Router();
  router.use(authenticate, authorize(ROLES.ADMIN));
  router.get('/:domain', validate({ params: domainParams, query: analyticsQuery }), unknownDomainIs404, requirePermissionBy((req) => DOMAIN_PERMISSION[req.params.domain]), route(async (req, res) => {
    await assertPlatformWide(req);
    const { domain } = req.params;
    return sendData(res, await getDomainAnalytics(domain, req.query.days));
  }));
  return router;
}

const viewQuery = z.object({
  from: z.string().regex(/^\d{4}-\d{2}-\d{2}$/).optional(),
  to: z.string().regex(/^\d{4}-\d{2}-\d{2}$/).optional(),
  compare: z.enum(['true', 'false']).optional(),
  timezone: z.string().max(40).optional(),
  categoryId: z.string().max(120).optional(),
  brandId: z.string().max(120).optional(),
  sku: z.string().max(64).optional(),
  warehouseId: z.string().max(64).optional(),
  fulfillmentType: z.enum(['SELLER', 'ARISE']).optional(),
});
const viewParams = z.object({ view: z.enum(['overview', 'products', 'traffic', 'operations', 'finance']) });

// Mount path: /api/seller/v1/dashboard (next to the header bell's alerts): the seller's home snapshot and recent activity.
export function createSellerDashboardRouter() {
  const router = Router();
  router.use(authenticate, authorize(ROLES.SELLER, ROLES.SELLER_STAFF));
  router.get('/summary', route(async (req, res) => sendData(res, await getSellerSummary(sellerScope(req)))));
  router.get('/activity', route(async (req, res) => sendData(res, await getSellerActivity(sellerScope(req)))));
  return router;
}

// Mount path: /api/seller/v1/analytics. Every view is scoped to the signed-in seller.
export function createSellerAnalyticsRouter() {
  const router = Router();
  router.use(authenticate, authorize(ROLES.SELLER, ROLES.SELLER_STAFF));
  router.get('/filters', route(async (req, res) => sendData(res, await getAnalyticsFilters(sellerScope(req)))));
  router.get('/recommendations', route(async (_req, res) => sendData(res, []))); // nothing generates recommendations yet
  router.get('/:view', validate({ params: viewParams, query: viewQuery }), route(async (req, res) => sendData(res, await getAnalyticsView(sellerScope(req), req.params.view, req.query))));
  return router;
}

